BITS = [[4, 6, 5, 7, 5, 7, 7, 5], [0, 0, 0, 0, 6, 8, 7, 5]]
W2, W3 = [0, 21, 43, 64], [0, 9, 18, 27, 37, 46, 55, 64]
W4 = [0, 4, 9, 13, 17, 21, 26, 30, 34, 38, 43, 47, 51, 55, 60, 64]
PBITS = 0b11001011


def _interp(a, b, w, i):
    return (a * (64 - w[i]) + b * w[i] + 32) >> 6


def bloque(blk):
    v = int.from_bytes(blk, "little")
    pos = 0

    def leer(n):
        nonlocal pos
        r = (v >> pos) & ((1 << n) - 1)
        pos += n
        return r

    mode = 0
    while mode < 8 and leer(1) == 0:
        mode += 1
    if mode >= 8:
        return [(0, 0, 0, 0)] * 16
    partition, nparts, rotation, isb = 0, 1, 0, 0
    if mode in (0, 1, 2, 3, 7):
        nparts = 3 if mode in (0, 2) else 2
        partition = leer(4 if mode == 0 else 6)
    nep = nparts * 2
    if mode in (4, 5):
        rotation = leer(2)
        if mode == 4:
            isb = leer(1)
    ep = [[0, 0, 0, 0] for _ in range(6)]
    for c in range(3):
        for j in range(nep):
            ep[j][c] = leer(BITS[0][mode])
    if BITS[1][mode]:
        for j in range(nep):
            ep[j][3] = leer(BITS[1][mode])
    if mode in (0, 1, 3, 6, 7):
        for e in ep[:nep]:
            for c in range(4):
                e[c] <<= 1
        if mode == 1:
            i, j = leer(1), leer(1)
            for c in range(3):
                ep[0][c] |= i
                ep[1][c] |= i
                ep[2][c] |= j
                ep[3][c] |= j
        elif PBITS & (1 << mode):
            for e in ep[:nep]:
                p = leer(1)
                for c in range(4):
                    e[c] |= p
    hp = (PBITS >> mode) & 1
    for e in ep[:nep]:
        j = BITS[0][mode] + hp
        for c in range(3):
            e[c] = e[c] << (8 - j)
            e[c] |= e[c] >> j
        j = BITS[1][mode] + hp
        e[3] = e[3] << (8 - j)
        e[3] |= e[3] >> j
    if not BITS[1][mode]:
        for e in ep[:nep]:
            e[3] = 255
    ib = 3 if mode in (0, 1) else (4 if mode == 6 else 2)
    ib2 = 3 if mode == 4 else (2 if mode == 5 else 0)
    w = W2 if ib == 2 else (W3 if ib == 3 else W4)
    w2 = W2 if ib2 == 2 else W3

    def pset(i, j):
        if nparts == 1:
            return 0 if (i | j) else 128
        return PART[nparts - 2][partition][i * 4 + j]

    idx = [[0] * 4 for _ in range(4)]
    for i in range(4):
        for j in range(4):
            n = ib - 1 if pset(i, j) & 0x80 else ib
            idx[i][j] = leer(n)
    out = []
    for i in range(4):
        for j in range(4):
            s = pset(i, j) & 3
            a0, a1 = ep[s * 2], ep[s * 2 + 1]
            k = idx[i][j]
            if not ib2:
                r, g, b, a = (_interp(a0[c], a1[c], w, k) for c in range(4))
            else:
                k2 = leer(ib2 if (i | j) else ib2 - 1)
                if not isb:
                    r, g, b = (_interp(a0[c], a1[c], w, k) for c in range(3))
                    a = _interp(a0[3], a1[3], w2, k2)
                else:
                    r, g, b = (_interp(a0[c], a1[c], w2, k2) for c in range(3))
                    a = _interp(a0[3], a1[3], w, k)
            if rotation == 1:
                a, r = r, a
            elif rotation == 2:
                a, g = g, a
            elif rotation == 3:
                a, b = b, a
            out.append((r, g, b, a))
    return out
